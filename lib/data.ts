export interface CaseSection {
  label: string;
  h2: string;
  body?: string[];
  type?: 'steps' | 'improvements';
  items?: string[] | StepGroup[];
}

export interface StepGroup {
  label: string;
  items: string[];
}

export interface CaseResult {
  n: string;
  d: string;
}

export interface SolutionSection {
  h3: string;
  description?: string;
  shots?: ShotItem[];
  videos?: VidItem[];
}

export interface ShotItem {
  screens: { src: string; position?: 'left' | 'center' | 'right' | string }[];
}

export interface VidItem {
  item: { src: string }[];
}

export type CaseBlock =
  | { type: 'heading'; h1: string; category: string; intro: string }
  | { type: 'hero'; src: string }
  | { type: 'metrics'; label: string; items: { value: string; label: string }[] }
  | { type: 'role'; items: string[] }
  | { type: 'problem'; text: string; cards?: { title: string; body: string }[] }
  | { type: 'quote'; text: string }
  | { type: 'research'; label: string; sections: { h3: string; body?: string; list?: { type: 'stroke' | 'bullet'; items: string[] } }[] }
  | { type: 'numbered-list'; label: string; items: string[] }
  | { type: 'solution-group'; sections: SolutionSection[] }
  | { type: 'before'; label: string; src: string }
  | { type: 'process'; sections: { h3: string; items: string[] }[] }
  | { type: 'improvements'; label: string; text: string }
  | { type: 'contacts' }
  | { type: 'shot'; src: string; }
  | { type: 'video'; src: string }

